// Execute the exact browser Plan Studio core against the checked-in case geometry.
import fs from 'node:fs';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
import {caseModel} from '../mvp/js/fallingwater-case.js';
const html=fs.readFileSync(new URL('../emb/modeler.html',import.meta.url),'utf8');
const start=html.indexOf('const STC = (() => {');
const end=html.indexOf('\n})();',start)+6;
assert(start>=0&&end>start);
const engine=html.slice(start,end),STC=Function(engine+';return STC;')();
const sha=s=>createHash('sha256').update(s).digest('hex');
const number=n=>{assert(Number.isFinite(n));return +n.toFixed(3);};
const runs=[.05,.15].map(open=>{
 const original=caseModel(open),model=STC.migrate(structuredClone(original.studio));
 const validation=STC.validate(model);assert.deepEqual(validation.errors,[]);const scene=validation.S;
 assert(new Set(scene.rooms.map(r=>r.lv)).size>=3);   // the main house's three levels, and the guest house
 assert(scene.ops.filter(o=>o.ext&&o.o.kind==='win').length>=8);
 const a=STC.airflow(model,scene);assert(a.total>0);
 const d=STC.daylight(model,scene,{step:.5,wp:.8,tau:.7});assert(d.pts.length>0);
 return {open,modelHash:sha(JSON.stringify(original)),airflow:number(a.total),ach:number(a.ach),daylightFactor:number(d.pts.reduce((s,p)=>s+p.df,0)/d.pts.length),rooms:scene.rooms.map((r,i)=>({level:r.lv,name:r.name,area:number(r.area),ach:number(a.rooms[i].ach),direct:number(a.rooms[i].direct),daylightFactor:number(d.rooms[i].mean)}))};
});
assert(runs[1].airflow>runs[0].airflow);
const data={generated:new Date().toISOString(),engine:'Plan Studio pressure-network airflow and CIE overcast daylight factor',engineHash:sha(engine),modelHash:sha(JSON.stringify(caseModel())),conditions:{windFromDeg:225,windSpeedAt10m:2.5,outdoorC:18,indoorC:24,terrain:'suburban',workplaneM:.8,glazingTransmittance:.7,gridM:.5},runs};
const output=new URL('../mvp/js/fallingwater-results.js',import.meta.url);
if(process.argv.includes('--check')){
 const {default:previous}=await import(output.href);assert.deepEqual({...data,generated:previous.generated},previous);
}else fs.writeFileSync(output,'// Generated by tools/build-fallingwater-results.mjs.\nexport default '+JSON.stringify(data,null,2)+';\n');
console.log(runs.map(r=>({open:r.open,Lps:r.airflow,ACH:r.ach,rooms:r.rooms.length})));

