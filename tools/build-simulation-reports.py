#!/usr/bin/env python3
"""Build mvp/research/simulation-reports.js from the Markdown sources in mvp/research/reports/*.md.

Each source: a front matter block between '---' lines (key: value; lists as '- item' under a key), then sections
'# Abstract', '# Body', '# References' (a numbered list, one reference per line). Edit the .md files, not the .js output.
"""
import json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / 'mvp' / 'research' / 'reports'
OUT = ROOT / 'mvp' / 'research' / 'simulation-reports.js'
REPO = 'https://github.com/plotcloudstudio/plotcloud/blob/main/'

def parse(path):
    text = path.read_text(encoding='utf-8')
    m = re.match(r'^---\n(.*?)\n---\n(.*)$', text, re.S)
    if not m: sys.exit(f'{path}: no front matter')
    meta, key = {}, None
    for line in m.group(1).split('\n'):
        if line.startswith('- ') and key: meta.setdefault(key, []).append(line[2:].strip()); continue
        k, _, v = line.partition(':'); key = k.strip(); v = v.strip()
        if v: meta[key] = v
    parts = re.split(r'^# (Abstract|Body|References)\s*$', m.group(2), flags=re.M)
    sec = {parts[i]: parts[i + 1].strip() for i in range(1, len(parts), 2)}
    for need in ('Abstract', 'Body', 'References'):
        if need not in sec: sys.exit(f'{path}: missing # {need}')
    refs = [re.sub(r'^\d+\.\s+', '', l).strip() for l in sec['References'].split('\n') if re.match(r'^\d+\.\s', l)]
    n_cited = max([int(x) for x in re.findall(r'\[(\d+)', sec['Abstract'] + sec['Body'])] or [0])
    if n_cited > len(refs): sys.exit(f'{path}: cites [{n_cited}] but lists {len(refs)} references')
    return meta, sec, refs

def post(path):
    meta, sec, refs = parse(path)
    code = [s.strip() for s in meta.get('code', '').split(',') if s.strip()]
    tests = [s.strip() for s in meta.get('tests', '').split(',') if s.strip()]
    data = 'Engine source: ' + ', '.join(f'[{c}]({REPO}{c})' for c in code) + '.'
    if tests: data += ' Tests: ' + ', '.join(f'[{t}]({REPO}{t})' for t in tests) + '.'
    data += ' This article\'s source: [' + path.name + '](' + REPO + 'mvp/research/reports/' + path.name + ').'
    return {
        'id': meta['id'], 'kind': 'blog', 'publishedAt': meta['published'] + 'T00:00:00-08:00',
        'content': {
            'format': 'article', 'journal': 'SimuSite Research Notes', 'journalNote': 'Technical note · not peer reviewed',
            'articleType': meta.get('type', 'Method and data report'), 'title': meta['title'],
            'authors': [{'name': 'SimuSite Studio', 'aff': 'a'}],
            'affiliations': [{'key': 'a', 'text': 'SimuSite, building performance software for architects. Prepared with AI assistance; human review pending.'}],
            'history': ['Published online ' + meta['publishedText'], 'Simulation audit of ' + meta['auditText'], 'Not submitted to a journal; not peer reviewed'],
            'keywords': meta['keywords'], 'highlights': meta['highlights'],
            'abstract': sec['Abstract'], 'body': sec['Body'],
            'backmatter': [
                {'title': 'CRediT authorship contribution statement', 'text': 'SimuSite Studio: Methodology, Software, Validation, Writing – original draft. The text was drafted with AI assistance (Claude, Anthropic) from the engine source and the test results named in it. Human subject-matter review is pending.'},
                {'title': 'Declaration of competing interest', 'text': 'The authors develop SimuSite, the software described in this article. No external funding was received.'},
                {'title': 'Data availability', 'text': data},
            ],
            'references': refs, 'category': 'research', 'simulation': meta['sim'],
            'summary': meta['summary'], 'image': meta.get('image', ''), 'imageAlt': meta.get('imageAlt', ''),
        },
    }

posts = [post(p) for p in sorted(SRC.glob('*.md'))]
order = {k: i for i, k in enumerate((SRC / 'ORDER').read_text().split())} if (SRC / 'ORDER').exists() else {}
posts.sort(key=lambda p: order.get(p['content']['simulation'], 999))
OUT.write_text('// Generated by tools/build-simulation-reports.py from mvp/research/reports/*.md; edit those, not this file\n'
               'export const simulationReports=' + json.dumps(posts, ensure_ascii=False) + ';\n', encoding='utf-8')
print(f'{len(posts)} reports -> {OUT.relative_to(ROOT)}')
