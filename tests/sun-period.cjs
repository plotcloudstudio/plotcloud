const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const base = process.env.TEST_BASE || 'http://127.0.0.1:8765';
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined, headless: true, args: ['--no-sandbox', '--enable-unsafe-swiftshader'] });
  try {
    const page = await browser.newPage({ viewport: { width: 1500, height: 1100 } });
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    await page.goto(base + '/emb/sunhours.html');
    await page.waitForFunction(() => window.__sun?.S.model && document.querySelector('#panelR'));
    await page.waitForFunction(() => !__sun.S.busy, null, { timeout: 90000 });
    const reveal = async () => { if (!(await page.locator('#period').isVisible())) await page.locator('[data-rail="3"]').click(); };
    await reveal();
    assert.equal(await page.locator('h2 > i').count(), 0, 'No numbered step badges');
    for (const id of ['h-model', 'h-site', 'h-an', 'h-set', 'export']) assert.equal(await page.locator('#' + id).evaluate(e => e.closest('aside').id), 'panelL');
    for (const id of ['h-res', 'legend']) assert.equal(await page.locator('#' + id).evaluate(e => e.closest('aside').id), 'panelR');
    const change = async (id, value) => { await page.locator('#' + id).fill(value); await page.locator('#' + id).dispatchEvent('change'); };
    await page.locator('#lvlSeg [data-l=custom]').click();
    await page.locator('#grid').selectOption('4'); await page.locator('#step').selectOption('30');
    await page.locator('#allDay').uncheck(); await change('t0', '08:30'); await change('t1', '10:45');
    const run = async () => {
      await page.locator('#run').click();
      await page.waitForFunction(() => window.__sun.S.lastR && !window.__sun.S.busy, null, { timeout: 90000 });
      await reveal();
      return page.evaluate(() => { const r = __sun.S.lastR; return { hours: Array.from(r.hours), win: r.win, period: r.period, grid: r.prep.s }; });
    };
    await change('date', '2026-03-20'); const a = await run();
    assert(Math.abs(a.win - 2.25) < 1e-8, 'Exact 08:30–10:45 window, including the final partial step');
    await change('date', '2026-03-21'); const b = await run();
    await page.locator('#period').selectOption('range');
    await change('date', '2026-03-20'); await change('dateEnd', '2026-03-21'); const total = await run();
    assert.equal(total.period.days, 2); assert.equal(total.hours.length, a.hours.length); assert.equal(total.grid, a.grid);
    assert(Math.abs(total.win - a.win - b.win) < 1e-8);
    total.hours.forEach((h, i) => assert(Math.abs(h - a.hours[i] - b.hours[i]) < 1e-5, 'Cumulative per-sample hours equal both actual daily runs'));
    assert.match(await page.locator('#legT').innerText(), /2026-03-20 to 2026-03-21/i);
    assert.match(await page.locator('#stats').innerText(), /cumulative/i);
    assert.equal(await page.locator('#t0').inputValue(), '08:30'); assert.equal(await page.locator('#t0').isEnabled(), true);
    // The same result, not a day preset, is exported with range provenance.
    await page.getByRole('button',{name:'Jump to Export',exact:true}).click();
    await page.locator('#export').click();
    await page.locator('#expmsg img').waitFor();
    const image = await page.locator('#expmsg img').evaluate(img => ({ src: img.src.slice(0, 22), bytes: img.src.length }));
    assert.equal(image.src, 'data:image/png;base64,'); assert(image.bytes > 10000);
    await page.screenshot({ path: process.env.SUN_SCREENSHOT || 'sun-period-check.png' });
    await page.getByRole('button',{name:'Jump to Analysis',exact:true}).click();
    await change('date', '2028-02-28'); await change('dateEnd', '2028-03-01');
    assert.deepEqual(await page.evaluate(() => __sun.dates()), ['2028-02-28', '2028-02-29', '2028-03-01']);
    await change('dateEnd', '2028-02-27'); await page.locator('#run').click();
    assert.match(await page.locator('#runmsg').innerText(), /on or after/);
    await change('dateEnd', '2029-03-01'); await page.locator('#run').click();
    assert.match(await page.locator('#runmsg').innerText(), /366/);
    await change('date', '2026-03-20'); await change('dateEnd', '2026-03-20');
    const one = await run(); assert.equal(one.period.days, 1);
    await change('t1', '08:00'); await page.locator('#run').click();
    assert.match(await page.locator('#runmsg').innerText(), /later than/);
    await change('t1', '10:45');
    await page.locator('#daySeg [data-d="06-21"]').click();
    assert.equal(await page.locator('#period').inputValue(), 'range', 'Presets only fill the date, not the analysis mode');
    assert.match(await page.locator('#date').inputValue(), /-06-21$/);
    await page.locator('#period').selectOption('single'); await page.locator('#allDay').check();
    assert.equal(await page.locator('#t0').isDisabled(), true);
    await change('date', '2026-03-20'); const full = await run(); assert(full.win > 10 && full.win < 14);
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.locator('.deskonly').isVisible(), true, 'Keep the existing desktop-only mobile guidance');
    // Exercise the production page shell too: its versioned model and Results archive.
    await page.setViewportSize({ width: 1500, height: 1100 });
    await page.goto(base + '/mvp/#/simulations/sunhours');
    await page.locator('#eng[data-pc-settings-ready=true][data-pc-visible-ready=true]').waitFor({timeout:90000});const engine = page.frameLocator('#eng');
    await page.waitForFunction(() => { const w = document.querySelector('#eng')?.contentWindow; return w?.__sun?.S.raw?.scene && !w.__sun.S.busy && w.__sun.S.date.endsWith('-03-20'); }, null, { timeout: 90000 });
    const ec = async (id, value) => { await engine.locator('#' + id).fill(value); await engine.locator('#' + id).dispatchEvent('change'); };
    await engine.locator('#pilotAdvanced').evaluate(e=>e.open=true);
    await engine.locator('#lvlSeg [data-l=custom]').click();
    await engine.locator('#grid').selectOption('4'); await engine.locator('#step').selectOption('30');
    await engine.locator('#pilotAdvanced').evaluate(e=>e.open=false);
    await engine.locator('#period').selectOption('range'); await ec('date', '2026-03-20'); await ec('dateEnd', '2026-03-21');
    await engine.locator('#allDay').uncheck(); await ec('t0', '08:30'); await ec('t1', '10:45');
    await page.locator('#autoSaveResult').uncheck();await engine.locator('#run').click();if(await engine.locator('#longGo').isVisible())await engine.locator('#longGo').click();
    await page.waitForFunction(() => { const s = document.querySelector('#eng').contentWindow.__sun.S; return !s.busy && s.lastR?.period?.days === 2; }, null, { timeout: 90000 });
    await page.locator('#save').click();
    await page.waitForFunction(() => JSON.parse(localStorage.getItem('pc-mvp-v1')).projects[0].runs.some(r => r.simId === 'sunhours'));
    const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('pc-mvp-v1')).projects[0].runs.filter(r => r.simId === 'sunhours').at(-1));
    assert.equal(saved.settings.analysisPeriod.start, '2026-03-20'); assert.equal(saved.settings.analysisPeriod.end, '2026-03-21');
    assert.equal(saved.settings.analysisPeriod.t0, 8.5); assert.equal(saved.settings.analysisPeriod.t1, 10.75);
    assert.equal(saved.settings.units, 'cumulative sunlight hours'); assert.equal(saved.settings.grid, 4);
    assert(saved.results.field.pts.length > 0, 'Real numerical field remains available for comparison');
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ ok: true, samples: total.hours.length, cumulativeHours: total.win, dailyHours: a.win, checks: 'layout, exact-minute weights, per-point cumulative sum, PNG export, leap day, invalid ranges, presets, full-day regression, mobile, versioned model and Results archive' }));
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
