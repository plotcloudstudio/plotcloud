const assert=require('assert'),fs=require('fs'),{chromium}=require('playwright');
const base=process.env.TEST_BASE||'http://127.0.0.1:8765';
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 const dir='/tmp/plotcloud-screenshots';fs.mkdirSync(dir,{recursive:true});
 const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
 page.on('pageerror',e=>errors.push(e.stack||e.message));
 const visit=async(path)=>{await page.goto(base+'/#/'+path);await page.waitForFunction(()=>document.body.classList.contains('pc-shell'));await page.locator(path.startsWith('home')?'.pc-home':'.pc-catalog').waitFor();};
 const noOverflow=async()=>assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Horizontal overflow at '+page.url());
 try{
  await visit('home');
  assert.deepEqual(await page.locator('#nav a').allTextContents(),['Tools','Resources','Pricing']);
  assert.equal(await page.locator('.pc-home>section').count(),4,'Home should have four focused sections');
  assert.equal(await page.locator('.pc-task').count(),3);
  assert.deepEqual(await page.locator('footer.site .fg h5').allTextContents(),['PlotCloud','Help & examples','Legal']);
  assert.equal(await page.locator('#sitelink').isVisible(),false,'Duplicate header entry still visible');
  assert(await page.locator('.pc-product-preview img').evaluate(img=>img.complete&&img.naturalWidth>0),'Product screenshot missing');
  await noOverflow();await page.evaluate(()=>scrollTo(0,0));await page.screenshot({path:dir+'/home-desktop.png',fullPage:true});
  await page.locator('.pc-task[href*="group=analysis"]').click();
  await page.locator('[data-shell-results]').waitFor();
  assert.equal(await page.locator('[data-shell-group="analysis"]').getAttribute('aria-pressed'),'true');
  assert(await page.locator('[data-catalog-tool="daylight"]').isVisible(),'Daylight missing from analysis');
  assert.equal(await page.locator('[data-catalog-tool="__plan"]').count(),0,'Category filter not applied');
  await page.locator('[data-shell-group="all"]').click();
  const oldIds=await page.evaluate(()=>[...new Set(TSECTIONS.flatMap(s=>s[4]))].filter(id=>!(TMETA[id]||[]).includes('dev')&&!((CMS.tools&&CMS.tools.hidden)||[]).includes(id)));
  const newIds=await page.locator('[data-catalog-tool]').evaluateAll(nodes=>nodes.map(n=>n.dataset.catalogTool));
  for(const id of oldIds)assert(newIds.includes(id),'Original tool omitted: '+id);
  assert(newIds.includes('__plan'),'Plan Studio not discoverable in Tools');
  const search=page.locator('[data-shell-search]');await search.fill('daylight');
  assert(/matching/.test(await page.locator('[role="status"]').innerText()),'Search status did not update');
  assert(await page.locator('[data-catalog-tool="daylight"]').isVisible());
  await search.fill('zzzznomatch');assert(await page.getByRole('heading',{name:'No matching tools',exact:true}).isVisible());
  await page.locator('[data-shell-reset]').click();
  assert.equal(await search.inputValue(),'');
  await page.locator('[data-shell-group="present"]').click();
  assert(await page.locator('[data-catalog-tool="architectural-render"]').isVisible(),'Independent renderer omitted');
  const method=page.locator('[data-catalog-tool="composer"] details');await method.locator('summary').click();assert(await method.getAttribute('open')!==null,'Method disclosure failed');
  await noOverflow();await page.evaluate(()=>scrollTo(0,0));await page.screenshot({path:dir+'/tools-desktop.png',fullPage:true});
  await page.reload();await page.waitForFunction(()=>document.body.classList.contains('pc-shell'));
  assert.equal(await page.locator('[data-shell-group="present"]').getAttribute('aria-pressed'),'true','Category did not survive reload');
  await page.setViewportSize({width:390,height:844});await visit('home');await noOverflow();
  await page.screenshot({path:dir+'/home-mobile.png',fullPage:true});
  await page.locator('#burger').click();assert.equal(await page.locator('#burger').getAttribute('aria-expanded'),'true');
  await page.locator('#mpanel a[data-go="tools"]').click();
  await page.locator('[data-shell-search]').waitFor({state:'visible'});
  assert.equal(await page.locator('#burger').getAttribute('aria-expanded'),'false');
  assert(await page.locator('[data-shell-search]').isVisible());await noOverflow();
  await page.screenshot({path:dir+'/tools-mobile.png',fullPage:true});
  await page.locator('[data-shell-search]').fill('scale');
  assert(await page.locator('[data-catalog-tool="scale"]').isVisible(),'Utility not searchable on mobile');
  await page.setViewportSize({width:320,height:740});await visit('home');await noOverflow();
  await page.setViewportSize({width:844,height:390});await visit('tools?group=analysis');await noOverflow();
  assert.equal(errors.length,0,errors.join(' | '));
  console.log('PASS simplified desktop/mobile shell, complete catalog, search, filters, disclosures and route persistence');
 }catch(e){await page.screenshot({path:dir+'/failure.png',fullPage:true});throw e;}finally{await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)});
