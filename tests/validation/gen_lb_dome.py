"""Writes mvp/js/environment/lb-dome.js: Ladybug's sky dome patches (ladybug.viewsphere.view_sphere.dome_patches and
dome_patch_weights) at resolution 1 (Tregenza, 145), 2 (Reinhart, 577) and 3 (1297), as LB View Percent uses them for Sky
View. Each patch is [x, y, z, weight] with Python's own repr of every float, so PlotCloud uses the very numbers Ladybug does.
Run with a python that has ladybug-core: python gen_lb_dome.py"""
import pathlib, ladybug
from ladybug.viewsphere import view_sphere as V
out = pathlib.Path(__file__).resolve().parents[2] / 'mvp/js/environment/lb-dome.js'
rows = []
for r in (1, 2, 3):
    _, vecs = V.dome_patches(r)
    w = V.dome_patch_weights(r)
    rows.append('  %d: [%s]' % (r, ','.join('[%r,%r,%r,%r]' % (v.x, v.y, v.z, k) for v, k in zip(vecs, w))))
out.write_text('// Generated by tests/validation/gen_lb_dome.py from ladybug-core %s (view_sphere.dome_patches and dome_patch_weights):\n'
               '// the sky patches of LB View Percent (Sky View) at resolution 1 (Tregenza), 2 (Reinhart) and 3. [x, y, z, weight]; do not edit.\n'
               'export const LB_DOME = {\n%s };\n' % (getattr(ladybug, '__version__', '0.45.0'), ',\n'.join(rows)))
print(out, out.stat().st_size)
